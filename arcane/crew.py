def crew_of(cleared: int) -> list[Member]:
    return [member for member in CREW if cleared >= member.joins]


def has(cleared: int, key: str) -> bool:
    return any(member.key == key and cleared >= member.joins for member in CREW)


def describe_crew() -> list[dict[str, Any]]:
    return [member.describe() for member in CREW]
