"""The crew: whoever the party rescued moves into headquarters and earns their keep.

Who has arrived follows from how far a mage got, so it needs no save of its own.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any

ATM_BONUS = 0.1
FRIDGE_HP = 15.0


@dataclass(frozen=True, slots=True)
class Member:
    key: str
    name: str
    title: str
    joins: int
    perk: str
    lines: tuple[tuple[int, str], ...]

    def line(self, cleared: int) -> str:
        """The freshest thing they have to say: it moves on with the story."""

        return next(text for at, text in reversed(self.lines) if cleared >= at)

    def describe(self) -> dict[str, Any]:
        return {
            "key": self.key,
            "name": self.name,
            "title": self.title,
            "joins": self.joins,
            "perk": self.perk,
            "lines": [list(entry) for entry in self.lines],
        }


